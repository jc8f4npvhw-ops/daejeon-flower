export type DaejeonDistrict = keyof typeof daejeonDeliveryRates;
export type DaejeonDeliveryArea = {
  district: DaejeonDistrict;
  dong: string;
  fee: number | null;
};

export function findDaejeonDeliveryArea(district: DaejeonDistrict | '', dong: string): DaejeonDeliveryArea | null {
  if (!district || !Object.hasOwn(daejeonDeliveryRates, district)) return null;
  const rates: Record<string, number | null> = daejeonDeliveryRates[district];
  if (!Object.hasOwn(rates, dong)) return null;
  return { district, dong, fee: rates[dong] };
}

export function daejeonAddress(area: DaejeonDeliveryArea, detail = '') {
  return ['대전', area.district, area.dong, detail.trim()].filter(Boolean).join(' ');
}

export function daejeonDeliveryFeeText(area: DaejeonDeliveryArea) {
  return area.fee === null ? '상담 후 안내' : area.fee.toLocaleString('ko-KR') + '원';
}
